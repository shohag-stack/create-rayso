// Builds a template from library/base, a theme and a list of library sections
import fs from 'fs-extra';
import path from 'path';
import { LIBRARY_DIR } from './library.js';

const GENERATED = 'Generated by create-rayso from the section library. When adding a section by hand, add it here too.';

const titleCase = (s) => s.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase());

// Where each library file lands in a template
function sectionTargets(s) {
  return [
    ['component.tsx', `frontend/components/sections/${s.component}.tsx`],
    ['query.ts', `frontend/(core)/fetch/sections/${s.id}.ts`],
    ['types.ts', `frontend/types/sections/${s.id}.ts`],
    ['schema.ts', `studio/schemaTypes/sections/${s.id}.ts`],
  ];
}

// ── Registries ────────────────────────────────────────────────────────────────

function studioSectionsIndex(sections) {
  const categories = [...new Set(sections.map((s) => s.category))];
  return `// ${GENERATED}
${sections.map((s) => `import { ${s.typeName} } from "./${s.id}";`).join('\n')}

export const sectionTypes = [${sections.map((s) => s.typeName).join(', ')}];

// Groups in the "Add item" menu of a page's sections
export const sectionGroups = [
${categories
  .map((c) => `  { name: "${c}", title: "${titleCase(c)}", of: [${sections.filter((s) => s.category === c).map((s) => `"${s.typeName}"`).join(', ')}] },`)
  .join('\n')}
];
`;
}

function studioSchemaIndex() {
  return `import { page } from "./documents/page";
import { siteSettings } from "./documents/siteSettings";
import { cta } from "./objects/cta";
import { imageWithAlt } from "./objects/imageWithAlt";
import { link } from "./objects/link";
import { seo } from "./objects/seo";
import { sectionTypes } from "./sections";

export const schemaTypes = [page, siteSettings, imageWithAlt, link, cta, seo, ...sectionTypes];
`;
}

function pageQuery(sections) {
  return `// ${GENERATED}
import { imageFields } from "@/(core)/fetch/fragments";
import { client } from "@/(core)/sanity/lib/client";
import type { PageData } from "@/types";
${sections.map((s) => `import { ${s.fields} } from "./sections/${s.id}";`).join('\n')}

const sectionsProjection = /* groq */ \`
  sections[]{
    _type,
    _key,
    "anchor": anchor.current,
${sections.map((s) => `    _type == "${s.typeName}" => { \${${s.fields}} }`).join(',\n')}
  }
\`;

const pageFields = /* groq */ \`
  _id,
  title,
  "slug": slug.current,
  menuColor,
  seo{ title, description, image{ \${imageFields} } },
  \${sectionsProjection}
\`;

export function getPage(id: string) {
  return client.fetch<PageData | null>(\`*[_type == "page" && _id == $id][0]{ \${pageFields} }\`, { id });
}

export function getPageBySlug(slug: string) {
  return client.fetch<PageData | null>(
    \`*[_type == "page" && _id != "home" && slug.current == $slug][0]{ \${pageFields} }\`,
    { slug }
  );
}

export function getPageSlugs() {
  return client.fetch<string[]>(\`*[_type == "page" && _id != "home" && defined(slug.current)].slug.current\`);
}
`;
}

function sectionTypesFile(sections) {
  return `// ${GENERATED}
${sections.map((s) => `import type { ${s.dataType} } from "./sections/${s.id}";`).join('\n')}

export type { ${sections.map((s) => s.dataType).join(', ')} };

export type PageSection =
${sections.map((s) => `  | ${s.dataType}`).join('\n')};
`;
}

function sectionRenderer(sections) {
  return `// ${GENERATED}
import type { PageSection } from "@/types";
${sections.map((s) => `import { ${s.component} } from "./${s.component}";`).join('\n')}

function renderSection(section: PageSection) {
  switch (section._type) {
${sections.map((s) => `    case "${s.typeName}":\n      return <${s.component} {...section} />;`).join('\n')}
    default:
      return null;
  }
}

// Each section gets a <section> wrapper whose id is the editor's anchor
export function SectionRenderer({ sections }: { sections: PageSection[] }) {
  return sections.map((section) => (
    <section key={section._key} id={section.anchor || undefined}>
      {renderSection(section)}
    </section>
  ));
}
`;
}

// ── Theme ─────────────────────────────────────────────────────────────────────

function themeCss(theme) {
  const block = (prefix, values) => Object.entries(values).map(([k, v]) => `  --${prefix}-${k}: ${v};`).join('\n');
  return `/* Theme "${theme.id}", generated from library/themes/${theme.id}.json. Edit freely. */
@theme {
  --font-heading: var(--font-heading-family), ${theme.fonts.heading.fallback};
  --font-body: var(--font-body-family), ${theme.fonts.body.fallback};
${block('color', theme.colors)}
${block('radius', theme.radius)}
}
`;
}

function fontsFile(theme) {
  const { heading, body } = theme.fonts;
  const imports = [...new Set([heading.google, body.google])].sort().join(', ');
  return `// Theme fonts. Swap them for any font in next/font/google.
import { ${imports} } from "next/font/google";

export const headingFont = ${heading.google}({ subsets: ["latin"], variable: "--font-heading-family", display: "swap" });
export const bodyFont = ${body.google}({ subsets: ["latin"], variable: "--font-body-family", display: "swap" });

export const fontVariables = \`\${headingFont.variable} \${bodyFont.variable}\`;
`;
}

// ── Seed content ──────────────────────────────────────────────────────────────

let keyCounter = 0;
const nextKey = () => `k${(keyCounter++).toString(36).padStart(6, '0')}`;

// Sanity needs a _key on every object in an array
function withKeys(value) {
  if (Array.isArray(value)) {
    return value.map((item) => (item && typeof item === 'object' && !Array.isArray(item) ? { _key: nextKey(), ...withKeys(item) } : withKeys(item)));
  }
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, withKeys(v)]));
  }
  return value;
}

function pageDocuments(pages, sectionsById) {
  return pages.map((p) => ({
    _id: p.id,
    _type: 'page',
    title: p.title,
    ...(p.id === 'home' ? {} : { slug: { _type: 'slug', current: p.slug ?? p.id } }),
    menuColor: p.menuColor ?? 'light',
    sections: p.sections.map((id) => ({ _key: nextKey(), _type: sectionsById.get(id).typeName, ...withKeys(sectionsById.get(id).seed) })),
  }));
}

// Seed documents → the shape the GROQ queries return, for previews without a Sanity project
function toQueryShape(value, slugs) {
  if (Array.isArray(value)) return value.map((v) => toQueryShape(v, slugs));
  if (!value || typeof value !== 'object') return value;
  const out = {};
  for (const [k, v] of Object.entries(value)) {
    if (k === '_sanityAsset') out.asset = { url: v.replace(/^(image|file)@/, '') };
    else if (k === 'anchor' && v?.current) out.anchor = v.current;
    else if (k === 'page' && v?._ref) Object.assign(out, { pageId: v._ref, slug: slugs[v._ref] });
    else out[k] = toQueryShape(v, slugs);
  }
  return out;
}

// ── CLAUDE.md inventory ───────────────────────────────────────────────────────

async function writeInventory(targetDir, sections) {
  const file = path.join(targetDir, 'CLAUDE.MD');
  if (!fs.existsSync(file)) return;
  let text = await fs.readFile(file, 'utf8');
  const header = '| Studio title | `_type` | Notes |\n|---|---|---|\n';
  const rows = sections.map((s) => `| ${s.title} | \`${s.typeName}\` | ${s.description} |\n`).join('');
  text = text.replace(header, header + rows);
  const ui = [...new Set(sections.flatMap((s) => s.uses?.ui ?? []))].sort();
  text = text.replace('| `components/ui/` | |', `| \`components/ui/\` | ${ui.join(', ')} |`);
  await fs.writeFile(file, text);
}

// Empty folders ship with a .gitkeep in the library; templates don't need them
async function removeGitkeeps(dir) {
  for (const entry of await fs.readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory() && entry.name !== 'node_modules') await removeGitkeeps(full);
    else if (entry.name === '.gitkeep') await fs.remove(full);
  }
}

// ── Main ──────────────────────────────────────────────────────────────────────

/**
 * @param {object} o
 * @param {string} o.targetDir
 * @param {object[]} o.sections   loaded library sections (loadSections)
 * @param {object} o.theme        loaded theme (loadTheme)
 * @param {{id: string, title: string, slug?: string, menuColor?: string, sections: string[]}[]} o.pages
 * @param {string} o.siteName
 * @param {boolean} [o.preview]   also write a /library page rendering every section from seed content
 */
export async function generateTemplate({ targetDir, sections, theme, pages, siteName, preview = false, libraryDir = LIBRARY_DIR }) {
  keyCounter = 0;
  const sectionsById = new Map(sections.map((s) => [s.id, s]));
  for (const p of pages) {
    const unknown = p.sections.filter((id) => !sectionsById.has(id));
    if (unknown.length) throw new Error(`Page "${p.id}" uses unknown sections: ${unknown.join(', ')}`);
  }

  // 1. Base template
  await fs.copy(path.join(libraryDir, 'base'), targetDir);
  await removeGitkeeps(targetDir);
  await fs.move(path.join(targetDir, 'gitignore'), path.join(targetDir, '.gitignore'), { overwrite: true });

  // 2. Sections
  for (const s of sections) {
    for (const [from, to] of sectionTargets(s)) await fs.copy(path.join(s.dir, from), path.join(targetDir, to));
  }

  // 3. Registries
  const write = (rel, content) => fs.outputFile(path.join(targetDir, rel), content);
  await write('studio/schemaTypes/sections/index.ts', studioSectionsIndex(sections));
  await write('studio/schemaTypes/index.ts', studioSchemaIndex());
  await write('frontend/(core)/fetch/page.ts', pageQuery(sections));
  await write('frontend/types/sections.ts', sectionTypesFile(sections));
  await write('frontend/components/sections/SectionRenderer.tsx', sectionRenderer(sections));

  // 4. Theme
  await write('frontend/app/theme.css', themeCss(theme));
  await write('frontend/app/fonts.ts', fontsFile(theme));

  // 5. Seed content
  const docs = [{ _id: 'siteSettings', _type: 'siteSettings', siteName }, ...pageDocuments(pages, sectionsById)];
  await write('seed/demo-content.ndjson', docs.map((d) => JSON.stringify(d)).join('\n') + '\n');

  // 6. CLAUDE.md inventory
  await writeInventory(targetDir, sections);

  // 7. Library preview (playground only)
  if (preview) {
    const slugs = Object.fromEntries(pages.map((p) => [p.id, p.slug ?? p.id]));
    const items = sections.map((s) => ({
      id: s.id,
      category: s.category,
      title: s.title,
      section: toQueryShape({ _key: s.id, _type: s.typeName, ...withKeys(s.seed) }, slugs),
    }));
    await write('frontend/library-preview.json', JSON.stringify(items, null, 2) + '\n');
    await write('frontend/app/library/page.tsx', libraryPage());
  }
}

function libraryPage() {
  return `import type { Metadata } from "next";
import { SectionRenderer } from "@/components/sections/SectionRenderer";
import preview from "@/library-preview.json";
import type { PageSection } from "@/types";

export const metadata: Metadata = { title: "Section library" };

type Item = { id: string; category: string; title: string; section: unknown };

// Every library section rendered from its seed content, no Sanity project needed
export default function LibraryPage() {
  return (
    <main>
      {(preview as Item[]).map((item) => (
        <div key={item.id} id={item.id}>
          <p className="sticky top-0 z-50 bg-black px-4 py-2 font-mono text-xs text-white">
            {item.category} / {item.id} · {item.title}
          </p>
          <SectionRenderer sections={[item.section as PageSection]} />
        </div>
      ))}
    </main>
  );
}
`;
}
